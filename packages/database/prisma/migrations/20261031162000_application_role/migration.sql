DO $$
BEGIN
    CREATE ROLE "nexo_app"
        LOGIN
        NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
EXCEPTION
    WHEN duplicate_object THEN
        ALTER ROLE "nexo_app"
            LOGIN
            NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
END
$$;

ALTER SCHEMA "mastra_storage" OWNER TO "nexo_app";
GRANT USAGE ON SCHEMA "public", "mastra_storage" TO "nexo_app";
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA "public" TO "nexo_app";
ALTER DEFAULT PRIVILEGES IN SCHEMA "public"
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "nexo_app";
